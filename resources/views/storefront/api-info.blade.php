        <p>Ta strona opisuje aplikację GPSwiss używaną do integracji sklepu GPSwiss z Allegro REST API.</p>

        <h2>Nazwa aplikacji:</h2>
        <p>GPswiss</p>

        <h2>Wersja aplikacji:</h2>
        <p>v1.0</p>

        <h2>User-Agent:</h2>
        <p><strong>GPswiss/v1.0 (+https://gpswiss.pl/api-info)</strong></p>

        <h2>Cel integracji:</h2>
        <p>Aplikacja służy do obsługi sprzedaży i synchronizacji danych pomiędzy sklepem GPSwiss a Allegro, w tym do:</p>
        <ul>
            <li>pobierania zamówień,</li>
            <li>aktualizacji statusów realizacji zamówień,</li>
            <li>tworzenia produktów i ofert na Allegro ze sklepu GPSwiss,</li>
            <li>zarządzania istniejącymi ofertami,</li>
            <li>aktualizacji dostępności produktów po sprzedaży.</li>
        </ul>

        <h2>Dostęp:</h2>
        <p>Aplikacja jest używana wyłącznie przez właściciela sklepu GPSwiss i nie jest publiczną usługą dla użytkowników zewnętrznych.</p>

